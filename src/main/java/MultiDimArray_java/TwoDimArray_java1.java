package MultiDimArray_java;

public class TwoDimArray_java1
{
    public static void main(String[]args){
        int arr[][]={{10,20,30},
                {40,50,60},
                {80,90,100}};
        System.out.println(arr[1][0]);//40
        System.out.println(arr[2][2]);//100
        System.out.println(arr[1][1]);//50
        System.out.println(arr.length);

    }
}
