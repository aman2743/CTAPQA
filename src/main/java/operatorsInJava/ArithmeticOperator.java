package operatorsInJava;

public class ArithmeticOperator {
    static void main() {
//  +,-,*,/,%
     int a=61;
     int b=30;
        System.out.println(a+b); //91
        System.out.println(a-b); //31
        System.out.println(a*b); //1830
        System.out.println(a/b); //2
        System.out.println(a%b); //1


    }
}
