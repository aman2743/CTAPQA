package operatorsInJava;

public class RelationalOperatorInJava {
    static void main() {
//  Relational Operator >,<,>=,<=,==,!=
    int a=10;
    int b=20;
        System.out.println(a>b);//false
        System.out.println(a<b);//true
        System.out.println(a==b);//false
        System.out.println(a!=b);//true
        System.out.println(a<=b);//true
        System.out.println(a>=b);//false

    }
}
