package operatorsInJava;

public class UnaryOperatorInJava {
    static void main() {
//   Unary Opertor ,++ (increment),--(Decrement)
//   Postfix: exp++, exp--
//   Prefix: ++exp, --exp
     int x=10;
        System.out.println(x++);
        System.out.println(x);
     int y=20;
        System.out.println(y--);
        System.out.println(y);
//    prefix
     int k=50;
        System.out.println(++k);
        System.out.println(k);
     int l=75;
        System.out.println(--l);

    }
}
